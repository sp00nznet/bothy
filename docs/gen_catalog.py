"""Generate docs/catalog.md from a catalog.

A catalog page listing hundreds of applications is not something anyone should
maintain by hand — it would be wrong within a week. Regenerate it instead:

    bothy --catalog containers.py import --out catalog.json
    python docs/gen_catalog.py catalog.json
"""
import json
import sys
from collections import Counter
from pathlib import Path

SRC = sys.argv[1] if len(sys.argv) > 1 else "catalog.json"
OUT = Path(sys.argv[2] if len(sys.argv) > 2 else "docs/catalog.md")

raw = json.loads(Path(SRC).read_text(encoding="utf-8"))


def mb(v) -> int:
    if isinstance(v, (int, float)):
        return int(v)
    s = str(v or "").strip().upper()
    if s.endswith("GB") or s.endswith("G"):
        return int(float(s.rstrip("GB").strip() or 0) * 1024)
    return int(float(s or 0)) if s.replace(".", "").isdigit() else 0


def kind(d) -> str:
    return "VM" if (d.get("deploy_type") == "vm" or d.get("iso")) else "LXC"


rows = []
for key, d in sorted(raw.items()):
    rows.append({
        "key": key,
        "name": d.get("name") or key,
        "category": d.get("category") or "Uncategorised",
        "kind": kind(d),
        "cores": d.get("cores") or 1,
        "mem": mb(d.get("memory")),
        "disk": str(d.get("disk_size") or ""),
        "upstream": d.get("upstream") or "",
        "imported": d.get("imported_from") or "",
        "desc": (d.get("description") or "").replace("|", "/").strip(),
    })

cats = Counter(r["category"] for r in rows)
lxc = Counter(r["category"] for r in rows if r["kind"] == "LXC")
vm = Counter(r["category"] for r in rows if r["kind"] == "VM")
linked = sum(1 for r in rows if r["upstream"])

L = []
w = L.append
w("# Application catalog\n")
w(f"**{len(rows)}** deployable definitions. "
  f"{linked} carry an upstream link ({100 * linked // max(1, len(rows))}%).\n")
w("Generated by `python docs/gen_catalog.py <catalog.json>` — do not edit by hand. "
  "See [catalog sources](catalog-sources.md) for where the definitions and links "
  "come from, and their licences.\n")

w("## By category\n")
w("| Category | LXC | VM | Total | With link |")
w("|---|---:|---:|---:|---:|")
for c, n in cats.most_common():
    have = sum(1 for r in rows if r["category"] == c and r["upstream"])
    w(f"| {c} | {lxc.get(c, 0)} | {vm.get(c, 0)} | {n} | {have} |")
w(f"| **Total** | **{sum(lxc.values())}** | **{sum(vm.values())}** | "
  f"**{len(rows)}** | **{linked}** |\n")

w("## Footprint\n")
buckets = [("Small", 0, 1024), ("Medium", 1024, 4096), ("Large", 4096, 10**9)]
w("| Size | Memory | Definitions |")
w("|---|---|---:|")
for label, lo, hi in buckets:
    n = sum(1 for r in rows if lo <= r["mem"] < hi)
    rng = f"< 1 GB" if lo == 0 else (f"{lo // 1024}–{hi // 1024} GB" if hi < 10**9
                                     else f"≥ {lo // 1024} GB")
    w(f"| {label} | {rng} | {n} |")
w("")

for c, _n in cats.most_common():
    w(f"## {c}\n")
    w("| Application | Key | Type | Cores | Memory | Disk | Upstream |")
    w("|---|---|---|---:|---:|---|---|")
    for r in [x for x in rows if x["category"] == c]:
        memlabel = f"{r['mem'] // 1024} GB" if r["mem"] >= 1024 else f"{r['mem']} MB"
        link = f"[site]({r['upstream']})" if r["upstream"] else "—"
        w(f"| {r['name']} | `{r['key']}` | {r['kind']} | {r['cores']} | "
          f"{memlabel} | {r['disk']} | {link} |")
    w("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(L), encoding="utf-8")
print(f"wrote {OUT}  ({len(rows)} definitions, {OUT.stat().st_size // 1024} KB)")
