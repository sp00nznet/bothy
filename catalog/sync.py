"""Regenerate catalog/ from the repos it is split from. `python catalog/sync.py`

  myhome (private)        containers.py, install_scripts.py   — copied, LAN map stripped
  gameservers (public)    <game>/*-setup.sh + lib/common.sh   — tested, hand-written
                          proxmox-deployer recipes            — LinuxGSM/Docker templates

myhome wins on a key it already has; then the hand-written setup scripts; the
deployer's templates only fill what is left. Never copies the gitignored
one-off *.py at the gameservers root — those carry live credentials.
"""
from __future__ import annotations

import importlib.util
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MYHOME = Path(os.environ.get("BOTHY_MYHOME", r"C:\myhome")) / "deployer" / "app"
GAMES = Path(os.environ.get("BOTHY_GAMESERVERS", r"F:\projects\tools\gameservers"))
# folder names the filename/folder rule gets wrong (ark-*.sh is ASA, not ARK: SE)
ALIAS = {"arkasa": "arksa", "counterstrike": "cs16"}
_IP = re.compile(r'^\s*"default_ip": "[0-9.]*",\s*$')


def _load(path: Path):
    spec = importlib.util.spec_from_file_location(f"_sync_{path.stem}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return mod


def bundle(script: Path, common: str) -> str:
    """One self-contained script: Bothy pushes a single file into the guest, so
    the `source ../lib/common.sh` line is replaced by the library itself.
    stdin is closed because the runner uses a PTY — a `read` prompt would
    otherwise wait out the whole install timeout; at EOF they take the skip path."""
    body = script.read_text(encoding="utf-8").replace("\r\n", "\n")
    src = 'source "${SCRIPT_DIR}/../lib/common.sh"'
    if src not in body:
        raise ValueError(f"{script}: no common.sh source line")
    lib = common.split("\n", 1)[1] if common.startswith("#!") else common
    body = body.replace(src, f"# ---- lib/common.sh (inlined by catalog/sync.py) ----\n{lib}\n# ---- end lib/common.sh ----")
    shebang, rest = body.split("\n", 1) if body.startswith("#!") else ("#!/bin/bash", body)
    return f"{shebang}\nexec </dev/null   # unattended: prompts get EOF\n{rest}"


def main() -> int:
    lines = (MYHOME / "containers.py").read_text(encoding="utf-8").splitlines(keepends=True)
    kept = [l for l in lines if not _IP.match(l)]
    (HERE / "containers.py").write_text("".join(kept), encoding="utf-8")
    defs = _load(HERE / "containers.py")
    keys = set(defs.CONTAINER_DEFINITIONS) | set(defs.VM_DEFINITIONS)
    print(f"containers.py: {len(keys)} definitions, {len(lines) - len(kept)} default_ip lines dropped")

    mine = {k for k, v in _load(MYHOME / "install_scripts.py").INSTALL_SCRIPTS.items()
            if isinstance(v, str) and v.strip()}
    extra: dict[str, str] = {}
    origin: dict[str, str] = {}
    unmatched: list[str] = []

    common = (GAMES / "lib" / "common.sh").read_text(encoding="utf-8").replace("\r\n", "\n")
    for sh in sorted(GAMES.glob("*/*-setup.sh")):
        # cs2-server-setup.sh -> "cs2"; fall back to the folder name
        key = next((k for k in (ALIAS.get(sh.parent.name), sh.name.split("-")[0], sh.parent.name)
                    if k in keys), None)
        if key is None:
            unmatched.append(sh.parent.name)
        elif key not in mine:
            extra[key], origin[key] = bundle(sh, common), f"gameservers/{sh.parent.name}"

    dep = _load(GAMES / "proxmox-deployer" / "app" / "install_scripts.py")
    for key in dep.INSTALL_SCRIPTS:
        if key in keys and key not in mine and key not in extra:
            script = dep.get_install_script(key)
            if script:
                extra[key], origin[key] = script, "gameservers/proxmox-deployer"

    out = (MYHOME / "install_scripts.py").read_text(encoding="utf-8").rstrip() + "\n\n\n"
    out += "# ---- generated by catalog/sync.py from the gameservers repo; do not edit below ----\n"
    out += "INSTALL_SCRIPTS.update({\n"
    for k in sorted(extra):
        out += f"    # {origin[k]}\n    {k!r}: {extra[k]!r},\n"
    out += "})\n"
    (HERE / "install_scripts.py").write_text(out, encoding="utf-8")

    by = {o: sum(1 for v in origin.values() if v == o) for o in sorted(set(origin.values()), key=len)}
    print(f"install_scripts.py: {len(mine)} from myhome + {len(extra)} from gameservers "
          f"({sum(1 for v in origin.values() if v != 'gameservers/proxmox-deployer')} hand-written, "
          f"{by.get('gameservers/proxmox-deployer', 0)} templated)")
    if unmatched:
        print("  no catalog definition for:", ", ".join(unmatched))
    return 0


if __name__ == "__main__":
    sys.exit(main())
